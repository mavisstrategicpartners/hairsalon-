import type { Product } from './catalog'

const IMAGE_UNAVAILABLE = '/images/products/image-unavailable.svg'

type LengthPrice = { length: string; price: number }

function rows(pairs: [number, number][]): LengthPrice[] {
  return pairs.map(([inch, price]) => ({ length: `${inch}"`, price }))
}

function addOn(source: LengthPrice[], extra: number, minInch?: number, maxInch?: number): LengthPrice[] {
  return source
    .filter((entry) => {
      const inch = Number.parseInt(entry.length, 10)
      if (minInch != null && inch < minInch) return false
      if (maxInch != null && inch > maxInch) return false
      return true
    })
    .map((entry) => ({ length: entry.length, price: entry.price + extra }))
}

function hair(product: Omit<Product, 'kind' | 'price'> & { price?: number; lengthPrices?: LengthPrice[] }): Product {
  const lengthPrices = product.lengthPrices
  const defaultLength = product.length ?? lengthPrices?.[0]?.length
  const price =
    product.price ??
    lengthPrices?.find((entry) => entry.length === defaultLength)?.price ??
    lengthPrices?.[0]?.price ??
    0
  const lengths = product.lengths ?? lengthPrices?.map((entry) => entry.length)
  return {
    ...product,
    kind: 'product',
    price,
    length: defaultLength,
    lengths,
    lengthPrices,
    image: product.imageUnavailable ? IMAGE_UNAVAILABLE : product.image,
  }
}

